#!/usr/bin/env bash
# Shared helpers for install.sh and set-scheme.sh. Not executable on its own.

THEME_NAME="Quickshell"

# theme_installed <gtk3_conf> <gtk4_conf>
# True once install.sh has pointed GTK at this theme, so set-scheme.sh can skip
# the GTK4 loader stub otherwise and not force an uninstalled theme on GTK4 apps.
theme_installed() {
  local conf
  for conf in "$1" "$2"; do
    grep -qs "^[[:space:]]*gtk-theme-name[[:space:]]*=[[:space:]]*$THEME_NAME[[:space:]]*$" "$conf/settings.ini" && return 0
  done
  grep -qs 'Generated by .*set-scheme\.sh' "$2/gtk.css"
}

# set_ini_key <file> <key> <value>
# Sets key=value inside the [Settings] section of a GTK settings.ini,
# preserving every other key already present. Idempotent.
set_ini_key() {
  local file="$1" key="$2" value="$3" tmp
  mkdir -p "$(dirname "$file")"
  [ -f "$file" ] || printf '[Settings]\n' > "$file"
  grep -q '^\[Settings\]' "$file" || sed -i '1i [Settings]' "$file"

  tmp="$(mktemp)"
  awk -v k="$key" -v v="$value" '
    # Replace the first existing definition of the key.
    $0 ~ "^[[:space:]]*" k "[[:space:]]*=" {
      if (!done) { print k "=" v; done = 1 }
      next
    }
    # Append immediately after [Settings] if the key was never defined.
    /^\[Settings\][[:space:]]*$/ && !seen {
      print; seen = 1; pending = 1; next
    }
    pending && !done { print k "=" v; done = 1; pending = 0; print; next }
    { print }
    END { if (!done) { if (!seen) print "[Settings]"; print k "=" v } }
  ' "$file" > "$tmp"
  mv "$tmp" "$file"
}

# remove_ini_key <file> <key>
# Deletes every definition of key from a GTK settings.ini. Used for keys that
# a toolkit actively warns about — libadwaita rejects
# gtk-application-prefer-dark-theme and wants AdwStyleManager:color-scheme.
remove_ini_key() {
  local file="$1" key="$2" tmp
  [ -f "$file" ] || return 0
  tmp="$(mktemp)"
  awk -v k="$key" '$0 ~ "^[[:space:]]*" k "[[:space:]]*=" { next } { print }' \
    "$file" > "$tmp"
  mv "$tmp" "$file"
}

# backup_once <file>
# Copies file to file.pre-quickshell once, preserving whatever was there before
# this theme was ever installed. Never clobbers an earlier backup, and never
# backs up a file this theme generated — otherwise re-running install.sh would
# capture our own stub and --uninstall would "restore" it instead of removing.
backup_once() {
  local file="$1"
  [ -e "$file" ] || return 0
  [ -e "$file.pre-quickshell" ] && return 0
  grep -q 'Generated by .*set-scheme\.sh' "$file" 2>/dev/null && return 0
  cp -a "$file" "$file.pre-quickshell"
  echo "  backed up $file → $file.pre-quickshell"
}
