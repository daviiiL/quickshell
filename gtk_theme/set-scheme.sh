#!/usr/bin/env bash
# Switch the Quickshell GTK theme between light and dark.
#
#   ./set-scheme.sh dark
#   ./set-scheme.sh light
#
# GTK3 picks gtk.css vs gtk-dark.css automatically from
# gtk-application-prefer-dark-theme, so it only needs the settings.ini flag.
#
# GTK4 has no such mechanism and GTK 4.22's CSS parser has no light-dark(),
# so ~/.config/gtk-4.0/gtk.css is rewritten to import the right entry point.
set -euo pipefail

THEME_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib.sh
. "$THEME_DIR/lib.sh"

GTK3_CONF="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-3.0"
GTK4_CONF="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-4.0"

scheme="${1:-}"
case "$scheme" in
  dark)  prefer_dark=1; gs_scheme="prefer-dark";  gtk3_file="gtk-dark.css" ;;
  light) prefer_dark=0; gs_scheme="prefer-light"; gtk3_file="gtk.css"      ;;
  *) echo "usage: $(basename "$0") {dark|light}" >&2; exit 2 ;;
esac

# ── GTK4: rewrite the loader stub with an absolute import ──────────────
# Absolute path, and a real file rather than a symlink: GTK resolves relative
# @import URLs against the path it was given, so a symlink here would send
# "../tokens-dark.css" to ~/.config/tokens-dark.css instead of the theme dir.
mkdir -p "$GTK4_CONF"
cat > "$GTK4_CONF/gtk.css" <<EOF
/* Generated by $THEME_DIR/set-scheme.sh — do not edit.
 * Quickshell GTK4 theme, scheme: $scheme
 * Re-run set-scheme.sh to switch. Edit the theme itself in:
 *   $THEME_DIR/
 */
@import url("file://$THEME_DIR/gtk-4.0/$scheme.css");
EOF

# ── GTK3 settings.ini ──────────────────────────────────────────────────
# GTK3 selects gtk.css vs gtk-dark.css from this key, so GTK3 needs it.
set_ini_key "$GTK3_CONF/settings.ini" gtk-application-prefer-dark-theme "$prefer_dark"

# GTK4 must NOT have it: libadwaita logs
#   "Using GtkSettings:gtk-application-prefer-dark-theme with libadwaita is
#    unsupported. Please use AdwStyleManager:color-scheme instead."
# once per app launch, and ignores the key anyway. The scheme reaches GTK4
# through the loader stub above plus the gsettings color-scheme below.
remove_ini_key "$GTK4_CONF/settings.ini" gtk-application-prefer-dark-theme

# ── gsettings (read by libadwaita and the settings portal) ─────────────
if command -v gsettings >/dev/null 2>&1; then
  gsettings set org.gnome.desktop.interface color-scheme "$gs_scheme" || true
fi

echo "Quickshell GTK theme → $scheme"
echo "  GTK4 loader : $GTK4_CONF/gtk.css → gtk-4.0/$scheme.css"
echo "  GTK3        : gtk-application-prefer-dark-theme=$prefer_dark (picks gtk-3.0/$gtk3_file)"
echo "  gsettings   : color-scheme=$gs_scheme"
echo
echo "Restart GTK apps to pick up the change."
